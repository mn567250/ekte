def marked_tests(test_dir: Path = HERE) -> dict[str, list[str]]:
    """Static scan of tests/a11y/test_*.py: step -> test functions marked with it."""
    out: dict[str, list[str]] = {}
    for path in sorted(test_dir.glob("test_*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        consts: dict[str, list[str]] = {}
        for node in tree.body:
            if isinstance(node, ast.Assign) and isinstance(node.value, (ast.Tuple, ast.List)):
                vals = [e.value for e in node.value.elts if isinstance(e, ast.Constant) and isinstance(e.value, str)]
                for t in node.targets:
                    if isinstance(t, ast.Name):
                        consts[t.id] = vals
        for node in ast.walk(tree):
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) or not node.name.startswith("test"):
                continue
            for d in node.decorator_list:
                if not (isinstance(d, ast.Call) and isinstance(d.func, ast.Attribute) and d.func.attr == "bitv"):
                    continue
                for a in d.args:
                    vals = (
                        consts.get(a.value.id, []) if isinstance(a, ast.Starred) and isinstance(a.value, ast.Name)
                        else [a.value] if isinstance(a, ast.Constant) and isinstance(a.value, str) else []
                    )
                    for v in vals:
                        lst = out.setdefault(v, [])
                        if node.name not in lst:
                            lst.append(node.name)
    return out


def docs_table(cat: dict[str, Any] | None = None, tests: dict[str, list[str]] | None = None) -> str:
    cat = cat or catalogue()
    tests = marked_tests() if tests is None else tests
    lines = [
        "| Step | WCAG 2.1 | Level | Title | Automation | How | Tests |",
        "|---|---|---|---|---|---|---|",
    ]
    for c in cat["steps"]:
        names = ", ".join(f"`{t}`" for t in tests.get(c["step"], [])) or "—"
        how = c["how"].replace("|", "\\|")
        lines.append(f"| {c['step']} | {c['wcag']} | {c['level']} | {c['title']} | {c['automation']} | {how} | {names} |")
    extra = sorted(set(tests) - {c["step"] for c in cat["steps"]}, key=_step_key)
    for step in extra:
        names = ", ".join(f"`{t}`" for t in tests[step])
        lines.append(f"| {step} | — | — | beyond WCAG (EN 301 549 clause {step}) | auto | — | {names} |")
    return "\n".join(lines)


def update_docs(path: Path = DOCS) -> bool:
    text = path.read_text(encoding="utf-8")
    if DOCS_START not in text or DOCS_END not in text:
        raise SystemExit(f"{path}: coverage table markers not found")
    head, rest = text.split(DOCS_START, 1)
    _, tail = rest.split(DOCS_END, 1)
    new = f"{head}{DOCS_START}\n{docs_table()}\n{DOCS_END}{tail}"
    if new != text:
        path.write_text(new, encoding="utf-8")
        return True
    return False


def _test_sort_key(entry: dict[str, Any]) -> str:
    return str(entry.get("test", ""))


def merge_results(parts: list[dict[str, Any]]) -> dict[str, Any]:
    """Results of several runs over disjoint tests (CI shards, see
    ZING_A11Y_SHARD in tests/a11y/conftest.py) -> the results one run over
    all of them would have written (tests/a11y/results.py:build_results)."""
    if len(parts) == 1:
        return parts[0]
    merged: dict[str, Any] = {}
    for part in parts:  # metadata: languages, themes, pages, axe version
        for k, v in part.items():
            if k not in ("tests", "steps", "axe_rules", "generated_at"):
                merged.setdefault(k, v)
    stamps = [p["generated_at"] for p in parts if p.get("generated_at")]
    if stamps:
        merged["generated_at"] = max(stamps)
    tests: dict[str, Any] = {}
    steps: dict[str, list[dict[str, Any]]] = {}
    rules: dict[str, dict[str, Any]] = {}
    for part in parts:
        tests.update(part.get("tests") or {})
        for step, entries in (part.get("steps") or {}).items():
            steps.setdefault(step, []).extend(entries)
        for rid, e in (part.get("axe_rules") or {}).items():
            g = rules.setdefault(rid, {"steps": e["steps"], "help": e["help"], "counts": {}})
            for k, v in e["counts"].items():
                g["counts"][k] = g["counts"].get(k, 0) + v
    merged["tests"] = dict(sorted(tests.items()))
    merged["steps"] = {
        step: sorted(entries, key=_test_sort_key)
        for step, entries in sorted(steps.items(), key=lambda kv: [int(x) for x in kv[0].split(".")])
    }
    merged["axe_rules"] = dict(sorted(rules.items()))
    return merged


def load_results(paths: list[Path]) -> dict[str, Any] | None:
    """The suite's results files (one per CI shard) merged, or None."""
    parts = []
    for path in paths:
        if path.exists():
            parts.append(json.loads(path.read_text(encoding="utf-8")))
        else:
            print(f"warning: {path} not found", file=sys.stderr)
    if not parts:
        print("warning: no results found, every step is reported as not tested", file=sys.stderr)
        return None
    return merge_results(parts)


def load_review(path: Path | None) -> dict[str, Any] | None:
    """A review file (llm_review.py's report or hand-written notes), or None;
    says on stderr whether an LLM review is used or ignored and why."""
    if path is None:
        return None
    if not path.exists():
        print(f"warning: {path} not found, no review notes merged", file=sys.stderr)
        return None
    llm = json.loads(path.read_text(encoding="utf-8"))
    if is_llm_review(llm):
        ok, why = usable_review(llm)
        print(f"{'using' if ok else 'ignoring'} {path}" + (f": {why}" if why else ""), file=sys.stderr)
    return llm


def write_report(path: Path, report: dict[str, Any]) -> None:
    path.write_text(json.dumps(report, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"wrote {path}: {summary_line(report)}")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m tests.a11y.conformance", description=__doc__.split("\n\n")[0])
    ap.add_argument(
        "--results", type=Path, nargs="+",
        help="per-step results written by the a11y suite (ZING_A11Y_RESULTS); several files (one per CI shard) are merged",
    )
    ap.add_argument(
        "--update", type=Path, metavar="REPORT",
        help="re-apply the review to an existing report (e.g. the committed bitv-report.json) instead of building it"
        " from --results; written back to REPORT unless --out is given",
    )
    ap.add_argument(
        "--llm", type=Path,
        help=f"review of the texts (tests/a11y/llm_review.py) or notes per step (default: ./{DEFAULT_LLM} if present)",
    )
    ap.add_argument("--no-llm", action="store_true", help="build the report from the tests alone")
    ap.add_argument("--out", type=Path, help=f"report to write (default: {DEFAULT_OUT.relative_to(ROOT)})")
    ap.add_argument("--docs", action="store_true", help="rewrite the coverage table in docs/ACCESSIBILITY.md")
    args = ap.parse_args(argv)
    if not args.results and not args.docs and not args.update:
        ap.error("give --results, --update and/or --docs")
    if args.results and args.update:
        ap.error("--results builds a new report, --update changes an existing one: give one of them")
    if args.docs:
        print(("updated " if update_docs() else "unchanged ") + str(DOCS.relative_to(ROOT)))
    llm_path = None if args.no_llm else (args.llm or (DEFAULT_LLM if DEFAULT_LLM.is_file() else None))
    if args.results:
        report = build_report(load_results(args.results), load_review(llm_path), commit=_git_commit())
        write_report(args.out or DEFAULT_OUT, report)
    if args.update:
        old = json.loads(args.update.read_text(encoding="utf-8"))
        report = apply_review(old, load_review(llm_path), now=_dt.datetime.now(_dt.timezone.utc))
        write_report(args.out or args.update, report)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
